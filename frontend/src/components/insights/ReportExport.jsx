
import {
  FileJson,
  FileText,
  Printer,
} from "lucide-react";

function getPayload(result) {
  return result?.result ?? result?.data ?? result ?? {};
}

function getFilename(target, extension) {
  let hostname = "security-report";

  try {
    hostname = new URL(
      target?.startsWith("http") ? target : `https://${target}`
    ).hostname;
  } catch {
    // Use the fallback filename.
  }

  return `cyalysis-${hostname.replace(/[^a-zA-Z0-9.-]/g, "-")}.${extension}`;
}

function downloadFile(content, filename, type) {
  const blob = new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");

  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  link.remove();

  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

function getChecks(payload) {
  const checks =
    payload?.results ??
    payload?.checks ??
    payload?.scan_results ??
    payload?.check_results ??
    [];

  return Array.isArray(checks) ? checks : [];
}

function getFindings(payload, checks) {
  if (Array.isArray(payload?.findings)) return payload.findings;

  return checks.filter(
    (check) =>
      check?.assessment?.state === "finding" ||
      String(check?.status ?? "").toLowerCase() === "finding"
  );
}

function exportJSON(result, target) {
  downloadFile(
    JSON.stringify(result, null, 2),
    getFilename(target, "json"),
    "application/json;charset=utf-8"
  );
}

function exportMarkdown(result, target) {
  const payload = getPayload(result);
  const checks = getChecks(payload);
  const findings = getFindings(payload, checks);
  const summary = payload?.summary ?? {};

  const lines = [
    "# CYALYSIS Security Assessment Report",
    "",
    `- **Target:** ${target || payload?.target || "Unavailable"}`,
    `- **Scan status:** ${payload?.status || "Unknown"}`,
    `- **Generated:** ${new Date().toLocaleString()}`,
    "",
    "## Summary",
    "",
    `- **Total checks:** ${summary.total ?? checks.length}`,
    `- **Findings:** ${summary.findings ?? findings.length}`,
    `- **Observations:** ${summary.observations ?? "Not provided"}`,
    `- **Passed:** ${summary.passed ?? "Not provided"}`,
    `- **Unable to assess:** ${summary.unable_to_assess ?? "Not provided"}`,
    `- **Unknown:** ${summary.unknown ?? "Not provided"}`,
    "",
    "## Findings",
    "",
  ];

  if (!findings.length) {
    lines.push("No findings were provided in the scan payload.", "");
  }

  findings.forEach((finding, index) => {
    lines.push(
      `### ${index + 1}. ${finding.title || finding.name || "Untitled finding"}`,
      "",
      `- **Severity:** ${finding.severity || "Unknown"}`,
      `- **Category:** ${finding.category || "Uncategorized"}`,
      "",
      finding.description || "No description provided.",
      "",
      `**Evidence:** ${finding.evidence || "Not provided."}`,
      "",
      `**Impact:** ${finding.impact || "Not provided."}`,
      "",
      `**Remediation:** ${finding.remediation || "Not provided."}`,
      ""
    );

    if (Array.isArray(finding.references) && finding.references.length) {
      lines.push("**References:**", "");

      finding.references.forEach((reference) => {
        if (typeof reference === "string") {
          lines.push(`- ${reference}`);
        } else {
          lines.push(
            `- ${reference?.title || reference?.name || "Reference"}${
              reference?.url ? `: ${reference.url}` : ""
            }`
          );
        }
      });

      lines.push("");
    }
  });

  lines.push("## All Check Results", "");

  checks.forEach((check) => {
    const name =
      check?.name ??
      check?.check_name ??
      check?.title ??
      "Unnamed check";

    const state =
      check?.assessment?.state ??
      check?.status ??
      "Unknown";

    lines.push(`- **${name}** — ${state}`);

    if (check?.evidence) {
      lines.push(`  - Evidence: ${check.evidence}`);
    }
  });

  lines.push(
    "",
    "---",
    "",
    "Generated by CYALYSIS. Results reflect the data returned by the scanner."
  );

  downloadFile(
    lines.join("\n"),
    getFilename(target, "md"),
    "text/markdown;charset=utf-8"
  );
}

function exportPDF() {
  window.print();
}

export default function ReportExport({ result, target }) {
  return (
    <>
      <button
        type="button"
        className="insights-sidebar-action"
        onClick={exportPDF}
        title="Open print dialog to save the report as PDF"
      >
        <Printer size={17} />
        <span>
          <strong>PDF</strong>
          <small>Print or save as PDF</small>
        </span>
      </button>

      <button
        type="button"
        className="insights-sidebar-action"
        onClick={() => exportJSON(result, target)}
        title="Download the scan payload as JSON"
      >
        <FileJson size={17} />
        <span>
          <strong>JSON</strong>
          <small>Full raw payload</small>
        </span>
      </button>

      <button
        type="button"
        className="insights-sidebar-action"
        onClick={() => exportMarkdown(result, target)}
        title="Download a readable Markdown report"
      >
        <FileText size={17} />
        <span>
          <strong>Markdown</strong>
          <small>Readable summary</small>
        </span>
      </button>
    </>
  );
}
